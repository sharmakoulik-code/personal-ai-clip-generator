"""Safe storage, YouTube URL handling, and local video probing."""
import json
import os
import re
import shutil
import subprocess
from pathlib import Path
from urllib.parse import parse_qs, urlsplit

from yt_dlp import YoutubeDL
from yt_dlp.utils import DownloadError

SUPPORTED_EXTENSIONS = {'.mp4', '.mov', '.mkv', '.webm', '.avi'}
STORAGE_DEFAULT = Path(__file__).resolve().parents[3] / 'storage'


def storage_root() -> Path:
    return Path(os.environ.get('CLIP_STORAGE_PATH', str(STORAGE_DEFAULT))).expanduser().resolve()


def storage_path(category: str, project_id: int, filename: str = '') -> Path:
    # IDs and filenames used here are generated by the application, never raw user paths.
    if category not in {'videos', 'thumbnails', 'temp'} or project_id < 1 or (filename and Path(filename).name != filename):
        raise ValueError('Invalid storage path')
    root = storage_root()
    result = (root / category / str(project_id) / filename).resolve()
    if not result.is_relative_to(root):
        raise ValueError('Invalid storage path')
    return result


def canonical_youtube_url(value: str) -> tuple[str, str]:
    try:
        url = urlsplit(value.strip())
        if url.scheme != 'https' or url.username or url.password or url.port not in (None, 443):
            raise ValueError
        host = (url.hostname or '').lower()
        path = url.path.split('/')
        if host in {'youtube.com', 'www.youtube.com', 'm.youtube.com'}:
            if url.path == '/watch':
                ids = parse_qs(url.query).get('v', [])
                video_id = ids[0] if len(ids) == 1 else ''
            elif len(path) == 3 and path[1] in {'shorts', 'live'}:
                video_id = path[2]
            else:
                raise ValueError
        elif host == 'youtu.be' and len(path) == 2:
            video_id = path[1]
        else:
            raise ValueError
        if not re.fullmatch(r'[A-Za-z0-9_-]{11}', video_id):
            raise ValueError
        return f'https://www.youtube.com/watch?v={video_id}', video_id
    except (ValueError, TypeError):
        raise ValueError('Enter a supported HTTPS YouTube video URL.') from None


def youtube_metadata(url: str) -> dict:
    canonical, video_id = canonical_youtube_url(url)
    options = {'quiet': True, 'no_warnings': True, 'noplaylist': True, 'skip_download': True,
               'ignoreconfig': True, 'socket_timeout': 20, 'retries': 0, 'extractor_retries': 0}
    try:
        with YoutubeDL(options) as ydl:
            info = ydl.extract_info(canonical, download=False)
    except DownloadError as exc:
        raise ValueError('Could not retrieve this video. It may be unavailable, private, restricted, or require access you do not have.') from exc
    if not info or info.get('id') != video_id or info.get('is_live'):
        raise ValueError('This video is unavailable or is an active live stream.')
    formats = []
    for f in info.get('formats') or []:
        if f.get('vcodec') != 'none' and f.get('height'):
            formats.append({'format_id': str(f.get('format_id', '')), 'height': f.get('height'),
                            'ext': f.get('ext'), 'filesize': f.get('filesize') or f.get('filesize_approx')})
    return {'video_id': video_id, 'url': canonical, 'title': info.get('title') or video_id,
            'thumbnail': info.get('thumbnail'), 'channel': info.get('channel') or info.get('uploader'),
            'duration': info.get('duration'), 'formats': formats}


def require_tools(*names: str) -> None:
    for name in names:
        executable = os.environ.get('CLIP_' + name.upper(), name)
        if not shutil.which(executable):
            raise ValueError(f'{name} was not found. Install FFmpeg and FFprobe and add them to PATH.')


def probe_video(path: Path) -> dict:
    ffprobe = os.environ.get('CLIP_FFPROBE', 'ffprobe')
    try:
        result = subprocess.run([ffprobe, '-v', 'error', '-protocol_whitelist', 'file,pipe', '-show_format', '-show_streams', '-of', 'json', str(path)],
                                capture_output=True, text=True, timeout=90, check=True)
        info = json.loads(result.stdout)
    except FileNotFoundError as exc:
        raise ValueError('FFprobe was not found. Install FFmpeg and add it to your PATH.') from exc
    except (subprocess.SubprocessError, json.JSONDecodeError) as exc:
        raise ValueError('Could not read the video. The file may be corrupt or unsupported.') from exc
    video = next((s for s in info.get('streams', []) if s.get('codec_type') == 'video' and not s.get('disposition', {}).get('attached_pic')), None)
    audio = next((s for s in info.get('streams', []) if s.get('codec_type') == 'audio'), None)
    if not video or not video.get('width') or not video.get('height'):
        raise ValueError('The file does not contain a readable video stream.')
    format_names = set((info.get('format', {}).get('format_name') or '').split(','))
    ext = path.suffix.lower()
    allowed_formats = {'.mp4': {'mp4', 'mov'}, '.mov': {'mov'}, '.mkv': {'matroska'},
                       '.webm': {'webm'}, '.avi': {'avi'}}
    if ext not in allowed_formats or not (format_names & allowed_formats[ext]):
        raise ValueError('The file contents do not match a supported video format.')
    try:
        duration = float(info.get('format', {}).get('duration') or video.get('duration') or 0) or None
    except (TypeError, ValueError):
        duration = None
    return {'duration': duration, 'width': video['width'], 'height': video['height'],
            'frame_rate': video.get('avg_frame_rate') or video.get('r_frame_rate'),
            'video_codec': video.get('codec_name'), 'audio_codec': audio.get('codec_name') if audio else None,
            'has_audio': bool(audio), 'size_bytes': path.stat().st_size}


def make_thumbnail(source: Path, target: Path) -> bool:
    target.parent.mkdir(parents=True, exist_ok=True)
    try:
        subprocess.run([os.environ.get('CLIP_FFMPEG', 'ffmpeg'), '-hide_banner', '-loglevel', 'error', '-y',
                        '-protocol_whitelist', 'file,pipe', '-i', str(source), '-frames:v', '1', '-vf', 'scale=320:-2', str(target)],
                       capture_output=True, timeout=60, check=True)
        return target.is_file()
    except (OSError, subprocess.SubprocessError):
        target.unlink(missing_ok=True)
        return False


def remove_project_files(project_id: int) -> None:
    for category in ('videos', 'thumbnails', 'temp'):
        path = storage_path(category, project_id)
        if path.exists():
            shutil.rmtree(path)
